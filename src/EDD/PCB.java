package EDD;

/**
 *
 * @author Eddy
 */
public class PCB {
    private int id;
    private String status;
    private String name;

    public PCB(int id, String name) {
        this.id = id;
        this.status = "new";
        this.name = name;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }
 
    public void update(String status, int pc, int mar) {
        setStatus(status);
    }

    /**
     * @return the id
     */
    public int getId() {
        return id;
    }

    /**
     * @return the name
     */
    public String getName() {
        return name;
    }

    /**
     * @param name the name to set
     */
    public void setName(String name) {
        this.name = name;
    }
    
    
}
